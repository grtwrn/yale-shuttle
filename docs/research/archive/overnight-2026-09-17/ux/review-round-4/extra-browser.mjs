import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium } from '/home/gwarren/projects/yale-shuttle-watcher/overnight-ux-2026-09-17/services/shuttle-v2/node_modules/playwright-core/index.mjs';
import { seedTestId } from '/home/gwarren/projects/yale-shuttle-watcher/overnight-ux-2026-09-17/services/shuttle-v2/scripts/testId.mjs';
const service = '/home/gwarren/projects/yale-shuttle-watcher/overnight-ux-2026-09-17/services/shuttle-v2';
const out = '/home/gwarren/projects/yale-shuttle-watcher/overnight-2026-09-17/ux/review-round-4';
const results = { checks: [], errors: [], submissions: [], completed: false };
const feed = JSON.parse(await fs.readFile(service + '/web/src/__fixtures__/buses-payload.json', 'utf8'));
feed.buses = [];
const reports = [801,802].map(id => ({id, createdAt:Date.now(), kind:'feedback', body:'Fixture report ' + id, status:'open', note:null, hasImage:false, archived:false, priority:'normal', followups:[]}));
let feedbackMode = 'failed', loadMode = 'ready', releaseLoad, actionMode = 'ready', releaseAction;
let ctx, page;
const browser = await chromium.launch({executablePath:'/usr/bin/chromium', args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
try {
  ctx = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,timezoneId:'America/New_York',serviceWorkers:'block'});
  await seedTestId(ctx);
  page = await ctx.newPage();
  page.setDefaultTimeout(8000);
  page.on('pageerror', error => results.errors.push(error.message));
  await page.route('**/*', async route => {
    const req=route.request(), u=new URL(req.url());
    if (u.hostname !== 'shuttle.test') return route.abort();
    if (u.pathname === '/api/buses') return route.fulfill({status:503,json:{}});
    if (u.pathname === '/api/weather') return route.fulfill({status:204});
    if (u.pathname === '/api/report') {
      const b=req.postDataJSON();
      results.submissions.push({kind:'feedback',text:b.note,priority:b.priority,image:!!b.image,anonPresent:!!req.headers()['x-anon-id']});
      if (feedbackMode === 'offline') return route.abort();
      return route.fulfill({status:feedbackMode==='ready'?200:503,json:{id:804}});
    }
    if (u.pathname === '/api/my-reports') {
      if (loadMode === 'pending') await new Promise(resolve => { releaseLoad=resolve; });
      return route.fulfill({status:loadMode==='failed'?503:200,json:{reports}});
    }
    const match=u.pathname.match(/^\/api\/my-reports\/(\d+)\/update$/);
    if (match) {
      const id=Number(match[1]), b=req.postDataJSON();
      results.submissions.push({kind:'action',id,action:b.action,text:b.text,image:!!b.image,anonPresent:!!req.headers()['x-anon-id']});
      if (actionMode==='pending') await new Promise(resolve=>{releaseAction=resolve;});
      const report=reports.find(r=>r.id===id);
      if(b.action==='followup') report.followups.push({text:b.text,at:Date.now(),hasImage:!!b.image});
      if(b.action==='set_priority') report.priority=b.priority;
      if(b.action==='archive') report.archived=true;
      if(b.action==='unarchive') report.archived=false;
      return route.fulfill({json:{ok:true}});
    }
    if(u.pathname.startsWith('/api/')) return route.fulfill({json:{results:[],routes:[]}});
    const file=u.pathname==='/'?'/index.html':u.pathname;
    try { return route.fulfill({body:await fs.readFile(service+'/web/dist'+file),contentType:file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':'text/html'}); }
    catch { return route.fulfill({status:404}); }
  });
  await page.goto('https://shuttle.test',{waitUntil:'domcontentloaded'});
  const feedbackOpen=page.getByRole('button',{name:'💬 Send feedback',exact:true});
  await feedbackOpen.click();
  const feedback=page.getByRole('textbox',{name:'Feedback',exact:true});
  await feedback.fill('Independent fixture with attached image');
  await page.getByRole('button',{name:'🔴 Urgent',exact:true}).click();
  const png={name:'fixture.png',mimeType:'image/png',buffer:await page.screenshot()};
  const pick=async(button, file)=>{
    await button.focus();
    const chooser=page.waitForEvent('filechooser');
    await button.press('Enter',{delay:60});
    await(await chooser).setFiles(file);
  };
  await pick(page.getByRole('button',{name:'📎 Attach screenshot',exact:true}),png);
  const feedbackImage=page.getByRole('img',{name:'attached screenshot',exact:true});
  await feedbackImage.waitFor();
  const imageSrc=await feedbackImage.getAttribute('src');
  await page.getByRole('button',{name:'Send',exact:true}).click();
  await page.getByRole('alert').getByText("Couldn't send — try again",{exact:true}).waitFor();
  await page.waitForTimeout(6500);
  assert(await page.getByRole('alert').getByText("Couldn't send — try again",{exact:true}).isVisible());
  assert.equal(await feedback.inputValue(),'Independent fixture with attached image');
  assert.equal(await feedbackImage.getAttribute('src'),imageSrc);
  assert.equal(await page.getByRole('button',{name:'🔴 Urgent',exact:true}).getAttribute('aria-pressed'),'true');
  feedbackMode='offline';
  await page.getByRole('button',{name:'Send',exact:true}).click();
  await page.getByRole('alert').getByText("Couldn't send — try again",{exact:true}).waitFor();
  assert.equal(await feedbackImage.getAttribute('src'),imageSrc);
  await feedback.locator('..').screenshot({path:out+'/independent-feedback-offline-390.png'});
  feedbackMode='ready';
  await page.getByRole('button',{name:'Send',exact:true}).press('Enter');
  await feedbackOpen.waitFor();
  await page.waitForFunction(()=>document.activeElement?.textContent.includes('Send feedback'));
  assert.deepEqual(results.submissions.slice(0,3).map(s=>[s.text,s.priority,s.image,s.anonPresent]),Array(3).fill(['Independent fixture with attached image','urgent',true,true]));
  results.checks.push('Feedback image/text/priority survive HTTP failure for >6s and aborted network request; successful retry keeps payload identity and focus, with live-feed failure');
  await page.getByRole('button',{name:'issues',exact:true}).click();
  const card=id=>page.getByText('Fixture report '+id,{exact:true}).locator('..');
  const reply=id=>card(id).getByRole('button',{name:'Reply',exact:true});
  await reply(801).press('Enter');
  const text=page.getByRole('textbox',{name:'Your reply',exact:true});
  await text.fill('Should not carry to another report');
  await pick(page.getByRole('button',{name:'📎 Add screenshot or paste one',exact:true}),png);
  await page.getByRole('img',{name:'Attached screenshot',exact:true}).waitFor();
  await reply(802).click();
  assert.equal(await text.inputValue(),'');
  assert.equal(await page.getByRole('img',{name:'Attached screenshot',exact:true}).count(),0);
  assert.equal(await text.getAttribute('id'),'reply-message-802');
  await text.fill('Reply specifically for report 802');
  loadMode='pending';
  await page.getByRole('button',{name:'Send',exact:true}).press('Enter');
  await page.getByRole('status').getByText('Reply sent',{exact:true}).waitFor();
  await reply(802).waitFor();
  assert(await reply(802).isDisabled());
  await page.waitForFunction(()=>document.activeElement===document.body);
  loadMode='ready'; releaseLoad();
  await page.waitForFunction(()=>document.activeElement?.textContent==='Reply');
  assert(await reply(802).evaluate(e=>e===document.activeElement));
  assert.equal(results.submissions.at(-1).id,802);
  assert.equal(results.submissions.at(-1).image,false);
  await reply(802).press('Space');
  await page.getByRole('button',{name:'Cancel',exact:true}).press('Enter');
  await page.waitForFunction(()=>document.activeElement?.textContent==='Reply');
  assert(await reply(802).evaluate(e=>e===document.activeElement));
  results.checks.push('Switching open reply clears completed attachment and text; POST uses report 802; focus waits for delayed refresh and returns to correct Reply on send/cancel');
  await reply(801).click();
  await text.fill('Do not steal another report action focus');
  loadMode='pending';
  await page.getByRole('button',{name:'Send',exact:true}).press('Enter');
  await page.getByRole('status').getByText('Reply sent',{exact:true}).waitFor();
  const priority=card(802).getByRole('combobox',{name:'Report priority',exact:true});
  await priority.focus();
  loadMode='ready'; releaseLoad();
  await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).some(b=>b.textContent==='Reply'&&b.disabled));
  assert(await priority.evaluate(e=>e===document.activeElement));
  results.checks.push('Reply refresh does not steal focus from another report priority control');
  await reply(801).click();
  await text.fill('Saved even if subsequent refresh fails');
  loadMode='failed';
  await page.getByRole('button',{name:'Send',exact:true}).press('Enter');
  await page.getByRole('alert').getByText('Couldn’t load your reports.',{exact:true}).waitFor();
  assert(await page.getByRole('status').getByText('Reply sent',{exact:true}).isVisible());
  loadMode='ready';
  await page.getByRole('button',{name:'Try again',exact:true}).press('Enter');
  await page.getByText('Saved even if subsequent refresh fails',{exact:true}).waitFor();
  results.checks.push('Acknowledged reply remains labeled sent when refresh fails; loading error is distinct, and keyboard retry recovers saved thread');
  await priority.selectOption('urgent');
  await page.getByRole('status').getByText('Saved',{exact:true}).waitFor();
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('select')).some(s=>s.value==='urgent'&&!s.disabled));
  assert.equal(await priority.inputValue(),'urgent');
  await card(802).getByRole('button',{name:'Archive',exact:true}).click();
  await page.getByRole('button',{name:'Show 1 archived',exact:true}).waitFor();
  await page.getByRole('button',{name:'Show 1 archived',exact:true}).press('Space');
  await card(802).getByRole('button',{name:'Unarchive',exact:true}).click();
  await page.getByRole('button',{name:'Show 1 archived',exact:true}).waitFor({state:'hidden'});
  assert(await card(802).isVisible());
  results.checks.push('Named priority action and archive/unarchive retain payload association and recover state');
  await page.screenshot({path:out+'/independent-issues-390.png',fullPage:true});
  assert.deepEqual(results.errors,[]);
  results.completed=true;
} finally {
  if(!results.completed&&page) results.failureSnapshot=await page.locator('body').ariaSnapshot().catch(()=>null);
  await ctx?.close();
  await browser.close();
  await fs.writeFile(out+'/extra-browser.json',JSON.stringify(results,null,2));
}
console.log(JSON.stringify(results,null,2));
