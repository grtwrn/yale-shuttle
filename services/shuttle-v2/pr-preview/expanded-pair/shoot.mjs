import { chromium } from "playwright-core";
import { seedTestId } from "../../scripts/testId.mjs";
const OUT = new URL(".", import.meta.url).pathname;
const BASE = process.env.BASE ?? "http://127.0.0.1:8120";
const b = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox","--disable-gpu","--disable-dev-shm-usage"] });
const ctx = await b.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, geolocation: { latitude: 41.3264, longitude: -72.9224 }, permissions: ["geolocation"] });
await seedTestId(ctx);
const p = await ctx.newPage();
await p.goto(BASE, { waitUntil: "domcontentloaded" });
await p.waitForTimeout(5000);
const box = p.getByPlaceholder(/where do you want to go/i).first();
await box.click({ timeout: 15000 });
await box.fill("Union Station");
await p.waitForTimeout(3500);
await p.getByText(/Union Station/).first().click({ timeout: 15000 }).catch(e => console.log("pick failed", e.message.slice(0,60)));
await p.waitForTimeout(6000);
await p.screenshot({ path: `${OUT}/1-collapsed.png`, fullPage: true });
const t1 = await p.evaluate(() => document.body.innerText);
console.log("COLLAPSED:\n" + t1.split("\n").filter(l => /Red|in \d+, \d+ min|min|:\d\da/.test(l)).slice(0, 14).join("\n"));
const opened = await p.evaluate(() => { const els=[...document.querySelectorAll("*")]; const t=els.find(e=>e.childElementCount===0 && /^13 min$|^\\d+ min$/.test(e.textContent.trim()) && e.closest("[class],div")); if(!t) return "no target"; let n=t; for(let i=0;i<6&&n;i++){ n=n.parentElement; if(n && n.onclick){ n.click(); return "clicked depth"+i; } } (t.closest("div")||t).click(); return "clicked fallback"; }); console.log("expand:", opened);
await p.waitForTimeout(4000);
await p.screenshot({ path: `${OUT}/2-expanded.png`, fullPage: true });
const t2 = await p.evaluate(() => document.body.innerText);
console.log("\nEXPANDED:\n" + t2.split("\n").filter(l => /Red|in \d+, \d+ min|#\d+|min|:\d\da/.test(l)).slice(0, 16).join("\n"));
await b.close();
